export type ScopeNature = "INSTALL" | "REMOVE" | "TEMPORARY" | "MAINTENANCE";
export type ScopeRecord = {
  id: number;
  version: number;
  status: string;
  created_by?: number;
  created_at?: string;
};
export type ModelObject = {
  id: number;
  model_version_id: number;
  source_identity: string;
  guid: string;
  express_id: number;
  ifc_class: string;
  name: string;
  properties: Record<string, unknown>;
  quantities: Record<string, unknown>[] | Record<string, unknown>;
  classification: unknown;
  discipline: string;
  level: string;
  area: string;
  zone: string;
  system: string;
  materials: string[];
  geometry_reference: unknown;
  scope_item_ids: number[];
  plan_item_ids: number[];
};
export type ModelVersion = ScopeRecord & {
  model_id: string;
  model_code: string;
  model_version_id: number;
  revision: number;
  source_file_name: string;
  source_hash: string;
  source_size_bytes?: number;
  schema: string;
  units: string | { code?: string; known?: boolean; basis?: string; [key: string]: unknown };
  is_current: boolean;
  validation_summary: Record<string, unknown>;
  diff: Record<string, unknown>;
  object_count: number;
  imported_at: string;
  imported_by: number;
  supersedes: number | null;
  objects_json: ModelObject[];
};
export type ScopeItem = ScopeRecord & {
  scope_code: string;
  name: string;
  description: string;
  parent_scope_item_id: number | null;
  scope_item_key: string;
  scope_type: string;
  scope_nature: ScopeNature;
  discipline: string;
  area: string;
  zone: string;
  system: string;
  location: string;
  quantity: number | string;
  unit: string;
  source_type: string;
  source_reference: string;
  source_revision: string;
  revision: number;
  baseline_reference?: number | null;
  model_object_ids: number[];
  source_quantity: number | string;
  approved_quantity: number | string | null;
  current_quantity: number | string;
  measurement_method: string;
  lineage_json?: { excel?: { import_id: number; row_number: number }; approved_change_id?: number };
  predecessor_id?: number | null;
};
export type ScopeRevision = ScopeRecord & {
  revision_code: string;
  reason: string;
  hash?: string;
  content_hash?: string;
  prepared_by?: number;
  reviewed_by?: number;
  candidate_items?: unknown[];
  diff_json?: Record<string, unknown>;
};
export type ScopeBaseline = ScopeRecord & {
  revision: number;
  scope_revision_id?: number;
  original_baseline_id?: number | null;
  revision_code?: string;
  baseline_code?: string;
  revision_id: number;
  is_original: boolean;
  is_current: boolean;
  content_hash?: string;
  snapshot_json?: Record<string, unknown>;
};
export type ExecutionPath = {
  code: string;
  name: string;
  mode: string;
  sequence: number;
  area?: string;
  zone?: string;
  system?: string;
  phase?: string;
  condition?: string;
};
export type ExecutionStrategy = ScopeRecord & {
  code: string;
  name: string;
  revision: number;
  paths: ExecutionPath[];
  segmentation_rules: Record<string, unknown>[];
};
export type Allocation = { scope_item_id: number; quantity: number; unit: string };
export type PlanItem = ScopeRecord & {
  code: string;
  name: string;
  revision: number;
  strategy_id?: number | null;
  parent_plan_item_id?: number | null;
  allocations: Allocation[];
  model_object_ids: number[];
  history_json?: unknown;
};
export type DerivedModel = ScopeRecord & {
  revision: number;
  plan_item_ids: number[];
  model_object_ids: number[];
  lineage_json?: unknown;
  content_hash?: string;
  split_rule: string;
  snapshot_json?: {
    split_rule?: string;
    objects?: Array<{ object_id: number; model_version_id: number; guid: string }>;
    memberships?: Array<{ plan_item_id: number }>;
  };
};
export type ExcelStage = ScopeRecord & {
  source_file_name: string;
  source_hash: string;
  validation_summary: Record<string, unknown>;
  rows_json?: unknown[];
  row_count?: number;
};
export type ScopeOverview = {
  context: Record<string, unknown>;
  allowed_actions: string[];
  configuration: Record<string, unknown>;
  models: ModelVersion[];
  imports: ExcelStage[];
  items: ScopeItem[];
  revisions: ScopeRevision[];
  baselines: ScopeBaseline[];
  strategies: ExecutionStrategy[];
  plan_items: PlanItem[];
  derived_models: DerivedModel[];
  version: number;
};
export type ScopeProfile = ScopeRecord & {
  code: string;
  name: string;
  revision: number;
  content_json: Record<string, unknown>;
};
export type Command = (path: string, payload: unknown, version?: number, method?: "POST" | "PUT") => Promise<unknown>;
